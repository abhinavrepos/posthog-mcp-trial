import assert from 'node:assert/strict'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { after, test } from 'node:test'
const dir = mkdtempSync(join(tmpdir(),'story-'))
Object.assign(process.env,{TRIAGE_DB:join(dir,'main.db'),TASKS_DB:join(dir,'tasks.db'),APP_EVENTS_FILE:'config/app-events.reval.json'})
const { tasksDb, forgetAnswers, setTaskQuery } = await import('../src/core/tasks.ts')
const { db } = await import('../src/core/db.ts')
const { clientStory, handoverPack } = await import('../src/core/story.ts')
const { rememberClientSurvey } = await import('../src/core/surveylocal.ts')
const { recordLaunch } = await import('../src/core/launches.ts')
const shift = (d: string,n: number) => new Date(Date.parse(d)+n*86400000).toISOString().slice(0,10)
const secret = 'ENV|SITE|acme|private-person@hidden.example'
after(()=>{tasksDb.close();db.close();rmSync(dir,{recursive:true,force:true})})
function seed() {
    for (const table of ['task_ingest','task_daily','task_users_daily','task_attempts','errors_daily','client_daily','ops_daily','user_daily','task_catalog','client_names']) tasksDb.exec(`DELETE FROM ${table}`)
    db.exec('DELETE FROM audit; DELETE FROM rescue_actions; DELETE FROM client_surveys; DELETE FROM survey_launches')
    for(let i=0;i<400;i++) tasksDb.prepare('INSERT INTO task_ingest VALUES (?,0,0,0,0,0,?)').run(shift('2026-06-28',-i),'2026-06-29')
    tasksDb.prepare('INSERT INTO client_names VALUES (?,?)').run('acme','Acme private-person@hidden.example')
    for (const [id,name] of [['t_Hedge','Hedge Designation'],['t_Trade','Trade private-person@hidden.example']]) tasksDb.prepare('INSERT INTO task_catalog VALUES (?,?,?,?,?,?)').run(id,id.slice(2),name,'save','2026-01-01','2026-06-28')
    const row = (day: string,id: string,n: number,done=n) => tasksDb.prepare('INSERT INTO task_daily VALUES (?,?,?,?,?,?,0,1,?)').run(day,'acme',id,n,done,n-done,JSON.stringify(Array(21).fill(0)))
    row('2026-05-05','t_Hedge',8); row('2026-06-08','t_Hedge',10); row('2026-06-15','t_Hedge',20,20); row('2026-06-22','t_Hedge',10,2)
    row('2026-06-22','t_Trade',4,3)
    for (const [day,id,user] of [['2026-06-22','t_Hedge',secret],['2026-06-22','t_Trade',secret],['2026-06-23','t_Hedge',secret],['2026-06-24','t_Hedge','second-person']]) tasksDb.prepare('INSERT INTO task_users_daily VALUES (?,?,?,?)').run(day,'acme',id,user)
    for (const day of ['2026-04-21','2026-04-28','2026-05-05']) for (const user of [secret,'second-person']) tasksDb.prepare('INSERT INTO task_users_daily VALUES (?,?,?,?)').run(day,'acme','t_Hedge',user)
    tasksDb.prepare('INSERT INTO errors_daily VALUES (?,?,?,?,?,?,?)').run('2026-06-24','acme','Hedge','save','Invalid private-person@hidden.example',5,4)
    tasksDb.prepare('INSERT INTO errors_daily VALUES (?,?,?,?,?,?,?)').run('2026-05-10','acme','Hedge','save','Invalid private-person@hidden.example',10,1)
    tasksDb.prepare('INSERT INTO ops_daily VALUES (?,?,?,?,?,?,?,?,?,?)').run('2026-06-24','acme','Hedge','xlsx export','export',7,1,0,0,0)
    tasksDb.prepare('INSERT INTO client_daily VALUES (?,?,?,?,?,?,?)').run('2026-06-24','acme',2,2,3,6,0)
    db.prepare('INSERT INTO rescue_actions (client,status,owner,note,due,updated_by,updated_at) VALUES (?,?,?,?,?,?,?)').run('acme','in_progress','pm@example.com','Ask private-person@hidden.example','2026-07-01','pm@example.com','2026-06-24')
    for (const [at,change] of [['2026-06-12',{status:'contacted'}],['2026-06-24',{status:'in_progress',note:`Ask ${secret}`}]] as const) db.prepare('INSERT INTO audit (t,who,action,details) VALUES (?,?,?,?)').run(at,'pm@example.com','rescue.updated',JSON.stringify({client:'acme',...change}))
    db.prepare('INSERT INTO audit (t,who,action,details) VALUES (?,?,?,?)').run('2026-06-25','pm@example.com','rescue.updated',JSON.stringify({client:'other',status:'resolved'}))
    rememberClientSurvey('draft-123','[Rescue] Feedback private-person@hidden.example',['acme'],'draft','2026-06-21')
    recordLaunch({survey_id:'launch-123',survey_name:'Targeted survey',ticket:'R-1',ticket_summary:null,launched_by:'pm@example.com',via:'chat',rules:[],clients:['acme']})
    db.prepare('UPDATE survey_launches SET at=?').run('2026-06-25')
    for (const [sid,day] of [['session-a','2026-06-24'],['session-b','2026-06-23'],['session-c','2026-06-22']]) tasksDb.prepare('INSERT INTO task_attempts VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)').run(day,'acme',secret,sid,'t_Hedge','[]','path',day+'T12:00:00Z',day+'T12:01:00Z',60,'done',0,null,10)
    forgetAnswers()
    setTaskQuery(async()=>{throw new Error('Story must not query PostHog')})
}
test('weekly counts, reason transitions, signals, audit actions, notes and targeted surveys form one privacy-safe story',async()=>{
    seed()
    const s=await clientStory({client:'acme',weeks:4})
    assert.deepEqual(s.weeks.map(w=>w.week_start),['2026-06-01','2026-06-08','2026-06-15','2026-06-22'])
    assert.deepEqual(s.weeks[3],{week_start:'2026-06-22',attempts:14,done:5,users:2,errors:5,unrecovered:4,exports:7,productive_done:6})
    assert.equal(s.coverage.complete,true)
    assert.ok(s.events.some(e=>e.date==='2026-06-07'&&e.kind==='reason_seen'&&e.text.includes('Stopped doing Hedge')))
    assert.ok(s.events.some(e=>e.date==='2026-06-14'&&e.kind==='reason_cleared'))
    assert.ok(s.events.some(e=>e.kind==='signal_seen'&&e.text.includes('gave up')))
    assert.ok(s.events.some(e=>e.kind==='action'&&e.actor==='pm@example.com'&&e.text==='changed follow-up from Contacted to In progress'))
    assert.ok(s.events.some(e=>e.kind==='reason_seen'&&e.text.includes('2 of 2 regular users stopped')))
    assert.ok(s.events.some(e=>e.kind==='note'||!!e.source))
    assert.ok(s.events.some(e=>e.kind==='survey'&&e.text.includes('draft')))
    assert.ok(s.events.some(e=>e.kind==='survey'&&e.text.includes('Targeted survey: launched')))
    assert.equal(s.events.some(e=>e.text.includes('resolved')),false)
    assert.deepEqual(s.events.map(e=>e.date),s.events.map(e=>e.date).sort().reverse())
    assert.equal(s.summary.split(/\.\s+/).length,3)
    assert.match(s.summary,/14 attempts and 5 done/); assert.match(s.summary,/in progress with pm@example.com/); assert.match(s.summary,/cannot tell us why/)
    assert.doesNotMatch(JSON.stringify(s),/private-person|hidden.example|second-person|ENV\|SITE|"user"/)
    db.prepare("UPDATE rescue_actions SET status='contacted'").run()
    assert.equal((await clientStory({client:'acme',weeks:4})).action?.status,'contacted','mutable actions bypass the history cache')
})
test('handover contains ranked established work, numbers, owners, surveys, two replay links and unknowns without users',async()=>{
    seed()
    const pack=await handoverPack('acme')
    for(const heading of ['Established tasks (90 days)','What changed recently','Open actions and owners','Surveys asked','Replays','What we do not know']) assert.ok(pack.includes('## '+heading))
    assert.match(pack,/Hedge Designation: 40 done/)
    assert.match(pack,/done rate fell/); assert.match(pack,/pm@example.com/); assert.match(pack,/Targeted survey/)
    assert.equal((pack.match(/\[Replay \d\]/g)||[]).length,2)
    assert.match(pack,/session-a/); assert.match(pack,/session-b/); assert.doesNotMatch(pack,/session-c/)
    assert.doesNotMatch(pack,/private-person|hidden.example|ENV\|SITE|second-person/)
})
test('missing days do not clear flags, validations bound cost, and no-history packs disclose unknowns',async()=>{
    seed()
    tasksDb.prepare("DELETE FROM task_ingest WHERE day='2026-06-13'").run(); forgetAnswers()
    const s=await clientStory({client:'acme',weeks:4})
    assert.equal(s.coverage.complete,false)
    assert.equal(s.events.some(e=>e.kind==='reason_cleared'&&e.date==='2026-06-14'),false)
    for(const weeks of [0,53,1.2,NaN]) await assert.rejects(clientStory({client:'acme',weeks}),/Weeks/)
    await assert.rejects(clientStory({client:''}),/client/)
    const empty=await handoverPack('unknown')
    assert.match(empty,/No completed tasks recorded/); assert.match(empty,/No replay links for recorded attempts/)
})
