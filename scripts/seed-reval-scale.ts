// Deterministic, invented Reval activity. Streams a day at a time, never a year's events in memory.
// npx tsx scripts/seed-reval-scale.ts --days 30 --clients 20 --sessions-per-client-day 25 --dry
import { createWriteStream } from 'node:fs'
import { once } from 'node:events'
import { config } from '../src/core/config.ts'

const args = process.argv.slice(2)
function option(name: string, fallback: number): number {
    const i = args.indexOf(name), n = i < 0 ? fallback : Number(args[i + 1])
    if (!Number.isInteger(n) || n < 1) throw new Error(`${name} must be a positive integer`)
    return n
}
const days = option('--days', 30), clients = option('--clients', 20), perDay = option('--sessions-per-client-day', 25)
const dry = args.includes('--dry'), outIndex = args.indexOf('--out'), out = outIndex < 0 ? undefined : args[outIndex + 1]
if (outIndex >= 0 && (!out || out.startsWith('--'))) throw new Error('--out needs a file path')
for (let i = 0; i < args.length; i++) {
    if (args[i] === '--dry') continue
    if (['--days', '--clients', '--sessions-per-client-day', '--out'].includes(args[i])) { i++; continue }
    throw new Error(`Unknown option: ${args[i]}`)
}
if (!dry && !out && !config.posthog.projectToken) throw new Error('Set POSTHOG_PROJECT_TOKEN, or use --dry / --out')
const stream = !dry && out ? createWriteStream(out) : undefined
// A fixed clock makes generated bytes reproducible. Override for a different historical interval.
const end = Date.parse(process.env.SEED_END_DAY || '2026-11-10')
if (!Number.isFinite(end)) throw new Error('SEED_END_DAY must be a valid date')
let random = 42
const r = () => ((random = (Math.imul(random, 1664525) + 1013904223) >>> 0) / 2 ** 32)
type Ev = { event: string; distinct_id: string; timestamp: string; properties: Record<string, unknown> }
const tasks = [
    { dialog: 'DlgDetailFasLinkAdvanced', title: 'Hedge Designation', button: 'Save', message: 'Link Id 13456 Added', base: 90 },
    { dialog: 'DlgRepAccrEnh', title: 'Accrual Report Parameters', button: 'Run', message: 'The async report has been scheduled', base: 45 },
    { dialog: 'DlgDetailIRSwap', title: 'IR Swap', button: 'Save', message: 'Trade Id 4356 Updated', base: 70 },
    { dialog: 'DlgDetailFX', title: 'FX Trade', button: 'Save', message: 'Trade Id 7843 Updated', base: 60 },
    { dialog: 'DlgCashflowReport', title: 'Cashflow Report', button: 'Export', message: 'Export completed', base: 35 },
]
let chunk: Ev[] = [], total = 0, sessions = 0
async function flush() {
    if (!chunk.length) return
    if (!dry) {
        if (stream) {
            if (!stream.write(chunk.map((e) => JSON.stringify(e)).join('\n') + '\n')) await once(stream, 'drain')
        } else {
            for (let attempt = 0; ; attempt++) {
                try {
                    const res = await fetch(`${config.posthog.host}/batch/`, { method: 'POST', headers: { 'content-type': 'application/json' },
                        body: JSON.stringify({ api_key: config.posthog.projectToken, historical_migration: true, batch: chunk }), signal: AbortSignal.timeout(30_000) })
                    if (!res.ok) throw new Error(`batch: ${res.status} ${(await res.text()).slice(0, 200)}`)
                    break
                } catch (e) {
                    if (attempt >= 4) throw e
                    await new Promise((resolve) => setTimeout(resolve, 500 * 2 ** attempt))
                }
            }
        }
    }
    total += chunk.length; chunk = []
}
async function emit(e: Ev) { chunk.push(e); if (chunk.length >= 500) await flush() }
for (let d = 0; d < days; d++) {
    const day = end - (days - d) * 86_400_000
    for (let c = 0; c < clients; c++) for (let s = 0; s < perDay; s++) {
        const code = `C${String(c + 1).padStart(3, '0')}`, distinct_id = `C1PRD|01|${code}|USER${s % 8 + 1}`
        // Canonical UUID-shaped, repeatable session ids; no collisions across the generated interval.
        const id = `${new Date(day).toISOString().slice(0, 10).replaceAll('-', '')}-${String(c).padStart(4, '0')}-4000-8000-${String(s).padStart(12, '0')}`
        let t = day + (8 + (s / perDay) * 8) * 3_600_000
        const add = async (delay: number, event: string, properties: Record<string, unknown>) => {
            t += delay * 1000
            await emit({ event, distinct_id, timestamp: new Date(t).toISOString(), properties: { $session_id: id, $time: t / 1000,
                client_id: code, client_name: `Treasury ${c + 1}`, ...properties } })
        }
        sessions++
        await add(0, 'PageView', { dialog_id: 'DlgListFavorites', dialog_name: 'My Views/My Favorites', action: 'OPEN', title: 'REVAL 27.0.0' })
        for (let task = 0; task < tasks.length; task++) {
            // Client 1 stops designation work halfway; client 2's swaps slow in the last fortnight.
            if (c === 0 && task === 0 && d >= Math.floor(days / 2)) continue
            const def = tasks[task], variant = (s + c + d + task) % (2 + task % 3)
            const speed = c === 1 && task === 2 && d >= days - 14 ? 1.5 : 1
            await add(20, 'Event', { dialog_id: 'menuCmb', action: def.title, control_type: 'SEARCH' })
            const path = variant === 0 ? [] : variant === 1 ? ['DlgTradeList'] : variant === 2 ? ['DlgListFavorites', 'DlgTradeList'] : ['DlgPortfolio', 'DlgTradeList']
            for (const dialog of path) await add(3 * speed, 'PageView', { dialog_id: dialog, dialog_name: dialog.slice(3), action: 'OPEN' })
            await add(3 * speed, 'PageView', { dialog_id: def.dialog, dialog_name: def.title, action: 'OPEN' })
            for (let field = 0; field < 3; field++) await add(def.base / 3 * (0.8 + r() * 0.4) * speed, 'Event',
                { dialog_id: def.dialog, dialog_name: def.title, tab_name: 'Main', action: ['Trade Date', 'Currency', 'Amount'][field], control_type: 'TEXTFIELD' })
            await add(2 * speed, 'Event', { dialog_id: def.dialog, action_name: def.button })
            const error = r() < (c === 2 ? 0.65 : 0.06)
            if (error) {
                await add(1 * speed, 'Event', { dialog_id: 'messagebox', action_name: ['Required accounting date is missing'] })
                if (r() < 0.5) continue
                await add(8 * speed, 'Event', { dialog_id: def.dialog, action: 'Accounting Date', control_type: 'DATEFIELD' })
                await add(2 * speed, 'Event', { dialog_id: def.dialog, action_name: def.button })
            }
            await add(1.2 * speed, 'Event', { dialog_id: 'toast', action_name: [def.message] })
        }
    }
    await flush()
    if (!dry) console.log(`${new Date(day).toISOString().slice(0, 10)}: ${total} events, ${sessions} sessions ${stream ? 'written' : 'sent'}`)
}
await flush()
if (stream) { stream.end(); await once(stream, 'finish') }
console.log(JSON.stringify({ days, clients, sessions_per_client_day: perDay, sessions, events: total, dry, out: out || null }))
