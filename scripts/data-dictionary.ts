// Deterministic reference deployment; never load a credential file.
process.env.TRIAGE_ENV_FILE = '/dev/null'
process.env.APP_EVENTS_FILE = 'config/app-events.reval.json'
process.env.CLIENT_FROM_DISTINCT_ID = '3'
process.env.DISTINCT_ID_SEPARATOR = '|'
process.env.PROP_CLIENT_ID = 'client_id'
process.env.PROP_CLIENT_NAME = 'client_name'
process.env.PROP_APP_VERSION = 'app_version'
process.env.PROP_PERSON_EMAIL = 'email'
const { dataDictionary } = await import('../src/core/datadictionary.ts')
const { writeFileSync, readFileSync } = await import('node:fs')
export const document = '# Data dictionary\n\nGenerated by `TRIAGE_ENV_FILE=/dev/null node --import tsx scripts/data-dictionary.ts` for the Reval reference configuration (client part 3). Deployments use their own configuration.\n\n' + dataDictionary({ format: 'full', private: false }) + '\n'
if (process.argv[1]?.endsWith('/data-dictionary.ts')) {
    const path = new URL('../docs/data-dictionary.md', import.meta.url)
    if (process.argv.includes('--check')) {
        if (readFileSync(path, 'utf8') !== document) throw new Error('docs/data-dictionary.md is stale; run scripts/data-dictionary.ts')
    } else writeFileSync(path, document)
}
